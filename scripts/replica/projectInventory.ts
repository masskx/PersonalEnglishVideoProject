import {existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync} from 'node:fs';
import path from 'node:path';
import {replicaProjects} from '../../src/replica/projects/registry';
import {resolveDeliveryPaths} from './deliveryPaths';
import {buildProjectDashboard} from './projectDashboard';

// Selected local metadata only. No dotenv, generation API, render, or release mutation.
const root = process.cwd();
const outputDir = path.join(root, 'docs/project-audit');
const relative = (file: string) => path.relative(root, file).replaceAll('\\', '/');
const link = (file: string) => file.split('/').map(encodeURIComponent).join('/');
const readJson = (file: string): Record<string, unknown> | null => {
  if (!existsSync(file)) return null;
  try { return JSON.parse(readFileSync(file, 'utf8')) as Record<string, unknown>; }
  catch { return {parseError: true}; }
};
const writeChanged = (file: string, value: string) => {
  if (existsSync(file) && readFileSync(file, 'utf8') === value) return;
  mkdirSync(path.dirname(file), {recursive: true});
  writeFileSync(file, value, 'utf8');
};
const projects = replicaProjects.map((project) => {
  const delivery = resolveDeliveryPaths(project, root);
  const directory = relative(delivery.directory);
  const hasPublished = delivery.directory === delivery.publishedDirectory;
  const release = readJson(delivery.release);
  const contentQa = existsSync(delivery.contentQa) ? readFileSync(delivery.contentQa, 'utf8') : '';
  const files = Object.fromEntries([
    `${project.slug}.mp4`, 'cover.png', 'cover-landscape.png', 'publish-copy.md',
    'release.json', 'content-qa.md', 'render-report.json', 'cover-report.json', 'cover-landscape-report.json',
  ].map((file) => [file, existsSync(path.join(delivery.directory, file))]));
  const record = {
    slug: project.slug, title: project.title, directory,
    configuredSeconds: project.storyboard.duration,
    sceneCount: project.storyboard.scenes.length,
    renderer: project.visualRenderer ?? 'default',
    words: project.cover?.words ?? [],
    searchTerms: [project.cover?.root, project.cover?.englishMeaning, project.cover?.chineseMeaning].filter(Boolean).join(" "),
    ttsModel: project.tts.model, voice: project.tts.voice, imageModel: project.image.model,
    releaseStatus: release?.parseError ? 'invalid-json' : release?.status ?? 'missing',
    folderSaysPublished: hasPublished,
    statusConflict: hasPublished !== (release?.status === 'published'),
    duplicateDirectories: false,
    contentQa: !contentQa ? 'missing' : /待人工核对|待核对|\[ \]/.test(contentQa) ? 'pending' : 'present-needs-review',
    files,
    locations: {video: relative(delivery.video), cover: relative(delivery.cover), landscapeCover: relative(delivery.landscapeCover),
      copy: relative(delivery.publishCopy), draft: relative(delivery.draftVideo), review: relative(delivery.review),
      audio: project.paths.publicAudioDir, illustrations: project.paths.alphaAssetDir, imageSources: project.paths.greenSourceDir},
    historicalReports: [
      ['render-report.json', delivery.video], ['cover-report.json', delivery.cover], ['cover-landscape-report.json', delivery.landscapeCover],
    ].map(([name, currentFile]) => {
      const report = readJson(path.join(delivery.directory, name));
      return {report: `${directory}/${name}`, recordedInput: report?.input ?? null, currentFile: relative(currentFile),
        currentFileExists: existsSync(currentFile), note: 'Historical report retained; current file mapping is not a new acceptance.'};
    }),
  };
  if (existsSync(delivery.directory)) {
    const readme = path.join(delivery.directory, 'README.md');
    const marker = '<!-- generated by project:inventory -->';
    if (existsSync(readme) && !readFileSync(readme, 'utf8').includes(marker)) {
      const backup = path.join(delivery.review, 'README.before-organization.md');
      if (!existsSync(backup)) { mkdirSync(path.dirname(backup), {recursive: true}); copyFileSync(readme, backup); }
    }
    const to = (file: string) => link(path.relative(delivery.directory, file).replaceAll('\\', '/'));
    const reportLinks = ['render-report.json', 'cover-report.json', 'cover-landscape-report.json'].filter((name) => files[name]).map((name) => `[${name}](${name})`).join(' · ');
    writeChanged(readme, `${marker}
# ${project.title}

[返回项目管理页](../../PROJECTS.html) · [操作流程](../../docs/项目管理流程.md)

此页自动维护，更新运行 npm run project:inventory；内容核对请填写 content-qa.md，发布状态通过 replica:release 维护。

| 要找什么 | 文件 |
| --- | --- |
| 最终视频 | [${project.slug}.mp4](${to(delivery.video)}) |
| 抖音竖封面 | [cover.png](${to(delivery.cover)}) |
| 小红书横封面 | [cover-landscape.png](${to(delivery.landscapeCover)}) |
| 发布文案 | [publish-copy.md](${to(delivery.publishCopy)}) |
| 内容检查 | [content-qa.md](${to(delivery.contentQa)}) |
| 本地状态 | [release.json](release.json) |
| 画面复核与历史资料 | [review/](review/) |

时长：${project.storyboard.duration.toFixed(2)} 秒；场景：${project.storyboard.scenes.length}；本地 release：${String(record.releaseStatus)}。
${record.statusConflict ? '**发布记录待核对：目录名有“发了”，release 尚未标为 published。保留原记录，不据此推断平台发布。**' : '本地状态不等于平台发布证据。'}
内容复核：${record.contentQa === 'missing' ? '缺少检查单' : '请查看检查单；文件存在不代表已通过'}。

配音：${project.tts.model} / ${project.tts.voice}；绘图：${project.image.model}。
[音频素材](${to(path.resolve(root, project.paths.publicAudioDir))}/) · [透明插图](${to(path.resolve(root, project.paths.alphaAssetDir))}/) · [绘图源图](${to(path.resolve(root, project.paths.greenSourceDir))}/) · [音频清单](${to(path.resolve(root, project.paths.audioManifestFile))})

历史技术报告：${reportLinks}。其中旧 input 路径按当时记录保留，当前路径以本页为准。
`);
  }
  return record;
});
mkdirSync(outputDir, {recursive: true});
const generatedAt = new Date().toISOString();
writeChanged(path.join(outputDir, 'inventory.json'), `${JSON.stringify({generatedAt, scope: 'Local file existence and configured metadata; not platform publication or content approval.', projects}, null, 2)}\n`);
const esc = (value: unknown) => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
const rows = projects.map((p) => `| ${p.slug} | ${p.configuredSeconds.toFixed(2)} | ${p.sceneCount} | ${esc(p.releaseStatus)} | ${p.folderSaysPublished ? '发了' : '普通目录'} | ${p.statusConflict ? '**待核对**' : '一致'} | ${p.contentQa === 'pending' ? '待人工核对' : p.contentQa === 'missing' ? '缺文件' : '有文件，待审'} | [打开](../../${link(p.directory)}/README.md) |`);
writeChanged(path.join(outputDir, 'INVENTORY.md'), `# 作品清单

自动扫描时间：${generatedAt}。更新命令：npm run project:inventory。日常使用 [项目管理页](../../PROJECTS.html)。

读取当前注册表和真实目录，时长来自配置。目录后缀、release 状态和平台实际发布是不同证据，冲突保留待核对。此命令只更新导航页和清单，不改视频、封面、文案、release 或内容检查单。

| 项目 | 配置秒数 | 场景 | release 状态 | 文件夹 | 状态核对 | 内容核对记录 | 产物 |
| --- | ---: | ---: | --- | --- | --- | --- | --- |
${rows.join('\n')}


[详细机器清单](inventory.json) · [项目入口](../../README.md)
`);
writeChanged(path.join(root, 'PROJECTS.html'), buildProjectDashboard(projects, generatedAt));
console.log(`Updated PROJECTS.html and ${projects.length} project indexes; ${projects.filter((p) => p.statusConflict).length} status conflicts remain explicit. No media or release records changed.`);
