async (page) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:8766/PROJECTS.html');
  const initial = await page.locator('#plan-items article').count();
  await page.getByRole('button', {name: '新增选题', exact: true}).click();
  if (await page.locator('#plan-items article').count() !== initial + 1) throw Error('Add failed');
  const card = page.locator('#plan-items article').last();
  await card.getByText('编辑选题与资料信息', {exact:true}).click();
  await card.getByRole('textbox', {name: /选题名称/}).fill('浏览器功能测试选题');
  await card.getByRole('textbox', {name: /选题名称/}).press('Tab');
  await page.reload();
  if (await page.getByText('浏览器功能测试选题', {exact:true}).count() !== 1) throw Error('Persistence failed');
  await page.getByLabel('导入 JSON', {exact:true}).setInputFiles('planning/content-plan.json');
  await page.waitForFunction(() => document.querySelectorAll('#plan-items article').length === 5);
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', {name:'导出计划与复盘', exact:true}).click();
  await (await downloaded).saveAs('work/experiments/mit-miss-smooth/review/plan-export.json');
  await page.getByRole('searchbox', {name:'搜索作品'}).fill('mit-miss');
  if (await page.locator('#grid .card:visible').count() !== 1) throw Error('Search failed');
  await page.getByRole('button', {name:'▶ 播放最终视频', exact:true}).click();
  if (!(await page.locator('#player').isVisible())) throw Error('Player dialog failed');
  await page.getByRole('button', {name:'关闭视频', exact:true}).click();
  await page.getByRole('searchbox', {name:'搜索作品'}).fill('');
  await page.screenshot({path:'work/experiments/mit-miss-smooth/review/workbench-desktop.png',fullPage:false});
  await page.setViewportSize({width:390,height:844});
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Mobile overflow');
  await page.screenshot({path:'work/experiments/mit-miss-smooth/review/workbench-mobile.png',fullPage:false});
  await page.setViewportSize({width:1280,height:900});
  if (errors.length) throw Error(errors.join('\n'));
  console.log('PASS: add/edit/persistence/import/export/search/player/mobile layout; no page errors. Restored seed plan.');
}
